function pkgJson(projectName, needsAuth) {
  return JSON.stringify(
    {
      name: projectName.toLowerCase().replace(/[^a-z0-9-]+/g, "-"),
      version: "1.0.0",
      private: true,
      main: "src/server.js",
      scripts: {
        start: "node src/server.js",
        test: "jest --runInBand --forceExit",
      },
      dependencies: {
        express: "^4.19.2",
        mongoose: "^8.5.1",
        cors: "^2.8.5",
        dotenv: "^16.4.5",
        "express-validator": "^7.2.0",
        ...(needsAuth ? { jsonwebtoken: "^9.0.2", bcryptjs: "^2.4.3" } : {}),
      },
      devDependencies: {
        jest: "^29.7.0",
        supertest: "^7.0.0",
      },
    },
    null,
    2
  );
}

function envExample(needsAuth) {
  return [
    "PORT=4000",
    "MONGODB_URI=mongodb://localhost:27017/app",
    ...(needsAuth ? ["JWT_SECRET=changeme_use_a_long_random_secret"] : []),
  ].join("\n") + "\n";
}

function dockerfile() {
  return `FROM node:20-alpine
WORKDIR /app
COPY package*.json ./
RUN npm install --omit=dev
COPY . .
EXPOSE 4000
CMD ["node", "src/server.js"]
`;
}

